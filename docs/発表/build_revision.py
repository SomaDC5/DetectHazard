# 新規スライドを「コピー版の何枚目の直後に入れるか」
INSERT_AFTER = {9: [slide_fusion, slide_attention, slide_transunet],
                36: [slide_bn]}

# 差し込みで番号がずれる章番号の付け替え（改訂版での位置 → 新しい章番号）
RELABEL = {13: "第2章 ⑤", 14: "第2章 ⑥"}


def move_to(prs, src_index, dst_index):
    """スライドの表示順を入れ替える。"""
    lst = prs.slides._sldIdLst
    ids = list(lst)
    lst.remove(ids[src_index])
    lst.insert(dst_index, ids[src_index])


def eyebrow_and_pagenum(slide):
    """章番号のテキストボックスと、ページ番号のテキストボックスを見つける。"""
    eb = pn = None
    for sh in slide.shapes:
        if not sh.has_text_frame:
            continue
        y, x = sh.top / 12700, sh.left / 12700
        if abs(y - Y_EYEBROW) < 3 and x < 60:
            eb = sh
        if x > 850 and y > 490:
            pn = sh
    return eb, pn


def main():
    prs = Presentation(str(SRC))
    n_before = len(prs.slides._sldIdLst)
    blank = prs.slide_masters[0].slide_layouts[6]

    # 新規スライドは末尾に生えるので、作ってから所定の位置へ動かす。
    # 後ろから処理すると、先に入れた分で位置がずれない。
    for after in sorted(INSERT_AFTER, reverse=True):
        for builder in reversed(INSERT_AFTER[after]):
            sl = prs.slides.add_slide(blank)
            builder(sl)
            move_to(prs, len(prs.slides._sldIdLst) - 1, after)

    slides = list(prs.slides)
    assert len(slides) == n_before + 4, len(slides)

    # 章番号の付け替えと、ページ番号の振り直し
    def set_text(shape, value):
        """書式を保ったまま文字だけ差し替える。先頭の run に入れ、残りは空にする。

        p.runs は呼ぶたびに別のオブジェクトを返すので、
        `r is p.runs[0]` では比較できない。一度リストにしてから添字で見る。
        """
        first = True
        for para in shape.text_frame.paragraphs:
            runs = list(para.runs)
            for j, r in enumerate(runs):
                r.text = value if (first and j == 0) else ""
            if runs:
                first = False

    for i, sl in enumerate(slides, 1):
        eb, pn = eyebrow_and_pagenum(sl)
        if i in RELABEL and eb is not None:
            set_text(eb, RELABEL[i])
        if pn is None:
            # 新しく足したスライドには番号の箱が無いので作る
            pn = tb(sl, 888.0, 508.3, 36.0, 17.3, [str(i)], 10.0, MUTED,
                    align=PP_ALIGN.RIGHT)
        else:
            set_text(pn, str(i))

    # 発表原稿をノートに入れる
    missing = []
    for i, sl in enumerate(slides, 1):
        note = NOTES.get(i)
        if note is None:
            missing.append(i)
            continue
        tf = sl.notes_slide.notes_text_frame
        tf.text = "\n".join(ln.strip() for ln in note.strip().splitlines())

    prs.save(str(DST))
    print(f"{n_before} 枚 → {len(slides)} 枚")
    print(f"原稿を入れた: {len(slides) - len(missing)} 枚"
          + (f" / 未記入: {missing}" if missing else ""))
    print(f"保存: {DST.name}")


if __name__ == "__main__":
    main()
